function displayHouses(list = houses) {

    const container =
        document.getElementById("houseListings");

    if (!container) {
        return;
    }


    if (list.length === 0) {

        container.innerHTML = `

            <div class="col-span-full text-center py-16">

                <div class="text-6xl">
                    🏠
                </div>

                <h2 class="text-2xl font-bold mt-4">
                    No houses found
                </h2>

                <p class="text-gray-500 mt-2">
                    Try changing your search or filter.
                </p>

            </div>

        `;

        return;
    }


    container.innerHTML =
        list.map(createPropertyCard).join("");


    const count =
        document.getElementById("houseCount");

    if (count) {

        count.textContent =
            `${list.length} properties found`;

    }

}




function filterHouses() {

    const searchInput =
        document.getElementById("houseSearch");

    const typeInput =
        document.getElementById("houseType");

    const budgetInput =
        document.getElementById("houseBudget");


    const search =
        searchInput
            ? searchInput.value.toLowerCase()
            : "";


    const type =
        typeInput
            ? typeInput.value
            : "";


    const budget =
        budgetInput
            ? Number(budgetInput.value)
            : 0;


    const filtered =
        houses.filter(house => {

            const matchesSearch =
                house.location
                    .toLowerCase()
                    .includes(search) ||

                house.name
                    .toLowerCase()
                    .includes(search);


            const matchesType =
                type === "" ||
                house.type === type;


            const matchesBudget =
                budget === 0 ||
                house.price <= budget;


            return (
                matchesSearch &&
                matchesType &&
                matchesBudget
            );

        });


    displayHouses(filtered);

}




