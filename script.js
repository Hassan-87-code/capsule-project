function searchFromHome() {

    const location =
        document.getElementById("homeLocation").value;

    const type =
        document.getElementById("homeType").value;

    const budget =
        document.getElementById("homeBudget").value;


    const params =
        new URLSearchParams();


    if (location) {
        params.set("location", location);
    }


    if (type) {
        params.set("type", type);
    }


    if (budget) {
        params.set("budget", budget);
    }


    window.location.href =
        "houses.html?" + params.toString();

}




function applyURLFilters() {

    const params =
        new URLSearchParams(window.location.search);


    const location =
        params.get("location");

    const type =
        params.get("type");

    const budget =
        params.get("budget");


    if (!location && !type && !budget) {

        displayHouses();

        return;

    }


    const searchInput =
        document.getElementById("houseSearch");


    const typeInput =
        document.getElementById("houseType");


    const budgetInput =
        document.getElementById("houseBudget");


    if (searchInput && location) {

        searchInput.value = location;

    }


    if (typeInput && type) {

        typeInput.value = type;

    }


    if (budgetInput && budget) {

        budgetInput.value = budget;

    }


    filterHouses();

}




